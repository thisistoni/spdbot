import assert from "node:assert/strict";
import {createHash} from "node:crypto";
import {createRequire} from "node:module";
import {readFileSync,readdirSync,statSync,writeFileSync} from "node:fs";
import {resolve,join} from "node:path";
import {fileURLToPath} from "node:url";
const root=resolve(fileURLToPath(new URL("../",import.meta.url)));
const builderRequire=createRequire(import.meta.resolve("electron-builder"));
const appBuilderRequire=createRequire(builderRequire.resolve("app-builder-lib"));
const asar=appBuilderRequire("@electron/asar");
const output=join(root,"release-preview"),resources=join(output,"win-unpacked/resources");
const archive=join(resources,"app.asar");
const authoritySource=asar.extractFile(archive,"electron/purchase-authority.mjs").toString();
const shipping=await import("data:text/javascript;base64,"+Buffer.from(authoritySource).toString("base64"));
const expected=JSON.parse(readFileSync(join(root,"build/preview-authority.json"),"utf8"));
assert.deepEqual(shipping.PURCHASE_AUTHORITY,expected);shipping.validateAuthority();
const pkg=JSON.parse(asar.extractFile(archive,"package.json").toString());
assert.equal(pkg.name,"spdbot-preview");assert.match(pkg.version,/^0\.1\.116-preview\./);
for(const file of asar.listPackage(archive))assert.doesNotMatch(file,/\/testing\/|\.node-test\./);
const server=readFileSync(join(resources,"server/index.js"),"utf8");
for(const key of [...expected.onlineKeys,...expected.leaseKeys])assert.ok(server.includes(key.kid));
const installer=readdirSync(output).find(name=>/^SPDBot-Preview-.*-setup\.exe$/.test(name));assert.ok(installer);
const bytes=readFileSync(join(output,installer));assert.equal(bytes.subarray(0,2).toString(),"MZ");
const manifest={filename:installer,bytes:statSync(join(output,installer)).size,sha256:createHash("sha256").update(bytes).digest("hex"),version:pkg.version};
writeFileSync(join(output,"windows.json"),JSON.stringify(manifest,null,2));
console.log(JSON.stringify({verified:true,environment:shipping.PURCHASE_AUTHORITY.environment,...manifest}));
